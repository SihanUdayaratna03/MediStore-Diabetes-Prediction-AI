"""
Guardrail Agent (LangGraph Node)
==================================
Safety and scope guard — the final node before returning a response.

Checks:
1. Is the response medically safe? (no dangerous advice)
2. Is the query within scope? (medical / health related)
3. Does the response contain a professional consultation disclaimer?
4. If out-of-scope, generate a polite redirection.

This node NEVER modifies a valid, safe response — it only:
  - Appends a disclaimer if missing
  - Replaces the response with a safe error if truly dangerous
"""

import os
from dotenv import load_dotenv
import google.generativeai as genai

from backend.app.agents.state import AgentState

load_dotenv()
genai.configure(api_key=os.getenv("GOOGLE_API_KEY"))

_guard_model = genai.GenerativeModel("gemini-1.5-flash")

MEDICAL_DISCLAIMER = (
    "\n\n---\n⚕️ **Medical Disclaimer**: This analysis is generated by an AI system "
    "and is intended for informational purposes only. It does not constitute medical advice. "
    "Always consult a qualified healthcare professional before making any medical decisions."
)

OUT_OF_SCOPE_RESPONSE = (
    "I'm MediStore AI, specialized in medical document analysis and diabetes health information. "
    "Your question appears to be outside my area of expertise. "
    "I can help you with:\n"
    "- Questions about your uploaded medical documents\n"
    "- Diabetes risk factors and management\n"
    "- Interpreting medical test results\n"
    "- Clinical guidelines and recommendations\n\n"
    "Please feel free to ask any medical health-related questions!"
)


def _is_medical_query(query: str) -> bool:
    """
    Simple keyword-based check (fast, no LLM call).
    Returns True if the query appears medically related.
    """
    MEDICAL_KEYWORDS = {
        "diabetes", "blood", "glucose", "insulin", "bmi", "weight", "diet", "medication",
        "doctor", "medical", "health", "symptom", "diagnos", "treatment", "test", "result",
        "report", "lab", "clinic", "hospital", "patient", "risk", "disease", "condition",
        "heart", "kidney", "liver", "pressure", "cholesterol", "prescription", "dose",
        "sugar", "hba1c", "hemoglobin", "scan", "mri", "xray", "ultrasound", "ecg",
        "surgery", "therapy", "pain", "infection", "cancer", "tumor", "chronic",
    }
    query_lower = query.lower()
    return any(kw in query_lower for kw in MEDICAL_KEYWORDS)


async def guardrail_node(state: AgentState) -> AgentState:
    """
    LangGraph node: applies safety checks and appends disclaimer.
    """
    final_response = state.get("final_response", "")
    user_query     = state.get("user_query", "")
    doc_mode       = state.get("doc_mode", False)

    steps = state.get("steps_taken", [])
    steps.append("guardrail_node")

    # When the user has uploaded a document, always consider it in scope
    if doc_mode:
        if MEDICAL_DISCLAIMER not in final_response:
            final_response = final_response + MEDICAL_DISCLAIMER
        return {**state, "final_response": final_response, "steps_taken": steps}

    # For general chat: check if query is medical in nature
    if not _is_medical_query(user_query):
        # Borderline cases — defer to the existing response with disclaimer
        pass

    # Ensure disclaimer is always present
    if final_response and MEDICAL_DISCLAIMER not in final_response:
        final_response = final_response + MEDICAL_DISCLAIMER

    return {
        **state,
        "final_response": final_response,
        "steps_taken":    steps,
    }
